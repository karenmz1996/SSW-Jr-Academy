function placeTour(el){
  const c=document.querySelector('.tcard'); if(!c||!el) return;
  const r=el.getBoundingClientRect(), w=c.offsetWidth, h=c.offsetHeight, W=innerWidth, H=innerHeight, gap=22, pad=16;
  const clamp=(v,lo,hi)=>Math.max(lo,Math.min(hi,v));
  let left,top,arrow;
  if(W-r.right>=w+gap+pad){left=r.right+gap;top=clamp(r.top+r.height/2-h/2,pad+50,H-h-pad);arrow='left';}
  else if(r.left>=w+gap+pad){left=r.left-gap-w;top=clamp(r.top+r.height/2-h/2,pad+50,H-h-pad);arrow='right';}
  else if(H-r.bottom>=h+gap+pad){top=r.bottom+gap+40;left=clamp(r.left+r.width/2-w/2,pad,W-w-pad);arrow='top';}
  else if(r.top>=h+gap+pad+50){top=r.top-gap-h;left=clamp(r.left+r.width/2-w/2,pad,W-w-pad);arrow='bottom';}
  else{top=H-h-pad;left=clamp(W/2-w/2,pad,W-w-pad);arrow='none';}
  c.style.left=left+'px';c.style.top=top+'px';c.dataset.arrow=arrow;
  if(arrow==='left'||arrow==='right')c.style.setProperty('--ay',clamp(r.top+r.height/2-top-7,20,h-30)+'px');
  if(arrow==='top'||arrow==='bottom')c.style.setProperty('--ax',clamp(r.left+r.width/2-left-7,20,w-30)+'px');
}
